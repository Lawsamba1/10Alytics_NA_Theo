-- The goal: Find which hours have the most trips + revenue so you know when to deploy more vehicles.

SELECT
    EXTRACT(HOUR FROM trip_time) AS hour,
    COUNT(*)                     AS trips,
    SUM(cost_naira)              AS revenue
FROM trips
WHERE EXTRACT(HOUR FROM trip_time) BETWEEN 6 AND 22
GROUP BY EXTRACT(HOUR FROM trip_time)
ORDER BY trips DESC;

